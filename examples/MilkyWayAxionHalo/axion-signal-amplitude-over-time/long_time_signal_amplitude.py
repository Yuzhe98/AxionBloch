"""Long-time stochastic axion-signal amplitude check.

This script tests the late-time signal amplitude for

    s(t) = [1 - exp(-t / (x T2star))]**x
           * gamma * B * T2star * sqrt(tau_a / (tau_a + T2star)).

Defaults follow the 2026-07-07 long-time scan:

* nu_a = 1 MHz;
* T2 = 10 s;
* T2star = (0.01, 0.03, 0.1, 0.3, 1, 3, 10, 30, 100) tau_a;
* rate = 20 / min(T2, T2star, tau_a);
* duration = 10 max(T2, T2star, tau_a), unless an explicit duration
  override is supplied.

The runtime estimate uses the method implemented in ``SimuTools.py``:

    numSteps = ceil(duration * rate) - 1
    t_setFields = T_SETFIELD_S * numFields * (numSteps + 1)
    t_trjry = T_SIMUSTEP_S * numSteps * magnet.numPt * numFields
    t_total = t_setFields + t_trjry

For batched runs, the estimate is summed over all batches.
"""

